"""Builds seed.sql from the DOH WFP Excel template.

Usage:
  python3 -I tools/build_seed.py PRINT_GAA.xlsx [--fy 2027] > database/seed.sql
  (or: sh tools/make_seed.sh PRINT_GAA.xlsx 2027   which also appends the default accounts)

Takes from the workbook:
  - hidden "Validation" sheet: Type of Function -> Objectives -> Success Indicators (A:C),
    Activity Classification (E), Budget Line Item (F), Source of Funds (R)
  - "General Info" sheet: office name and signatories (budgets start at 0 for the new year)
Encoding Sheet rows are NOT imported: each area encodes its own activities in the system.
"""
import sys
import warnings

import openpyxl

warnings.filterwarnings("ignore")
args = sys.argv[1:]
FY = int(args[args.index("--fy") + 1]) if "--fy" in args else 2027
wb = openpyxl.load_workbook(args[0], data_only=True)
val, gi, pg = wb["Validation"], wb["General Info"], wb["Print (GAA)"]


def q(v):
    if v is None:
        return "NULL"
    return "'" + str(v).strip().replace("\\", "\\\\").replace("'", "''") + "'"


def column(letter, first, last):
    seen = []
    for r in range(first, last + 1):
        v = val[f"{letter}{r}"].value
        if v is not None and str(v).strip() and str(v).strip() not in seen:
            seen.append(str(v).strip())
    return seen


out = ["-- generated by build_seed.py", "SET NAMES utf8mb4;", ""]

# Offices: only the two the default accounts need. The real areas are added in the app.
out.append("INSERT INTO offices (id,code,name) VALUES (1,'PLAN','Planning Office');")
out.append("INSERT INTO offices (id,code,name) VALUES (2,'MIS','Management Information Systems');")
out.append("")

# Column A -> B -> C (Validation!A3:C34)
obj_ids = {}
iid = 0
for r in range(3, 40):
    ft, ob, ind = val[f"A{r}"].value, val[f"B{r}"].value, val[f"C{r}"].value
    if not ft or not ob or not ind:
        continue
    ob, ind = ob.strip(), ind.strip()
    if (ft, ob) not in obj_ids:
        oid = obj_ids[(ft, ob)] = len(obj_ids) + 1
        out.append(f"INSERT INTO objectives (id,function_type,title,sort_order) VALUES ({oid},{q(ft)},{q(ob)},{oid});")
    iid += 1
    out.append(f"INSERT INTO indicators (id,objective_id,title,sort_order) VALUES ({iid},{obj_ids[(ft, ob)]},{q(ind)},{iid});")
out.append("")

# Column E (Validation!E3:E30, the Encoding Sheet dropdown range)
for i, n in enumerate(column("E", 3, 30), 1):
    out.append(f"INSERT INTO classifications (id,name,sort_order) VALUES ({i},{q(n)},{i});")
out.append("")

# Column F (Validation!F3:F60)
for i, n in enumerate(column("F", 3, 60), 1):
    out.append(f"INSERT INTO line_items (id,name,sort_order) VALUES ({i},{q(n)},{i});")
out.append("")

# Column Q (Validation!R3:R7: CONAP, 2026 GAA, ODA, Income, Others).
# "2026 GAA" is stored as "GAA" and displayed as "<fiscal year> GAA".
for i, n in enumerate(column("R", 3, 12), 1):
    name = "GAA" if n.endswith("GAA") else n
    out.append(f"INSERT INTO fund_sources (id,name,is_income,sort_order) VALUES ({i},{q(name)},{1 if name == 'Income' else 0},{i});")
out.append("")

# General Info signatories. "Approved By" is a formula there, so read it from Print (GAA) K11/K12.
out.append(
    "INSERT INTO settings (fiscal_year,office_name,prepared_by,prepared_pos,recommending_by,recommending_pos,approved_by,approved_pos) VALUES "
    f"({FY},{q(gi['E3'].value)},{q(gi['E5'].value)},{q(gi['I5'].value)},{q(gi['E7'].value)},{q(gi['I7'].value)},"
    f"{q(pg['K11'].value)},{q(pg['K12'].value)});"
)

print("\n".join(out))
print(f"-- FY {FY}: {len(obj_ids)} objectives, {iid} indicators", file=sys.stderr)
